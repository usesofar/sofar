#!/usr/bin/env node
// The Homebrew formula, rendered whole for a published version (r4-fixes E6):
//
//   node packaging/homebrew/formula.mjs [<version>] [--out <path>]
//
// With no version it takes sofar.sh's `latest` dist-tag: the tap carries
// stable releases only. It downloads sofar.sh's tarball and the four unix
// core tarballs from the registry, hashes each, and writes sofar.rb (or
// --out). Rendering the whole file replaces the old sed over two lines: a
// formula with a core resource per platform has ten release-varying lines.
//
// Why each core is a Homebrew resource instead of npm's optionalDependency:
// Homebrew installs npm packages with --ignore-scripts, so sofar.sh's
// postinstall never copies the core over bin/sofar-core, and with
// --min-release-age=1, so npm refuses an exact-pinned core published the
// same day. A resource is fetched and checksummed by brew itself, and the
// formula does what postinstall would.

import { createHash } from 'node:crypto'
import { writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { PLATFORMS, packageName } from '../npm/emit.mjs'

const REGISTRY = 'https://registry.npmjs.org'

/** The platforms Homebrew runs on, in the formula's order: Windows has no brew. */
export const BREW_PLATFORMS = PLATFORMS.filter((p) => p.platform !== 'win32')

/** A scoped package's tarball url: `@scope/name` → `@scope/name/-/name-<v>.tgz`. */
export function tarballUrl(name, version) {
  const base = name.startsWith('@') ? name.split('/')[1] : name
  return `${REGISTRY}/${name}/-/${base}-${version}.tgz`
}

/**
 * @param {string} version a published sofar.sh version
 * @param {Record<string, string>} sha256 tarball url → hex sha256, for sofar.sh and each BREW_PLATFORMS core
 * @returns {string} the formula
 */
export function renderFormula(version, sha256) {
  const sha = (url) => {
    const hex = sha256[url]
    if (!/^[0-9a-f]{64}$/.test(hex ?? '')) throw new Error(`no sha256 for ${url}`)
    return hex
  }
  const main = tarballUrl('sofar.sh', version)
  const os = { darwin: 'on_macos', linux: 'on_linux' }
  const cpu = { arm64: 'on_arm', x64: 'on_intel' }
  const blocks = []
  for (const platform of ['darwin', 'linux']) {
    const inner = BREW_PLATFORMS.filter((p) => p.platform === platform).map((p) => {
      const url = tarballUrl(packageName(p), version)
      return [
        `    ${cpu[p.arch]} do`,
        `      resource "core" do`,
        `        url "${url}"`,
        `        sha256 "${sha(url)}"`,
        `      end`,
        `    end`,
      ].join('\n')
    })
    blocks.push(`  ${os[platform]} do\n${inner.join('\n\n')}\n  end`)
  }
  return `${HEADER}class Sofar < Formula
  desc "Event-sourced initiative memory for coding agents"
  homepage "https://sofar.sh"
  url "${main}"
  sha256 "${sha(main)}"
  license "MIT"

  livecheck do
    url "${REGISTRY}/sofar.sh/latest"
    strategy :json do |json|
      json["version"]
    end
  end

  depends_on "node"

  # The native core for this machine (rendered by packaging/homebrew/formula.mjs).
${blocks.join('\n\n')}

  def install
    system "npm", "install", *std_npm_args
    pkg = libexec/"lib/node_modules/sofar.sh"

    # What sofar.sh's postinstall does, which --ignore-scripts skips: the
    # platform package where the CLI resolves it, and its binary over the
    # bin/sofar-core shim so hook shims exec native code with no node.
    arch = Hardware::CPU.arm? ? "arm64" : "x64"
    platform = OS.mac? ? "darwin" : "linux"
    core = pkg/"node_modules/@sofar.sh/core-#{platform}-#{arch}"
    rm_r core if core.exist?
    resource("core").stage { core.install Dir["*"] }
    chmod 0755, core/"sofar-core"
    rm pkg/"bin/sofar-core"
    cp core/"sofar-core", pkg/"bin/sofar-core"

    bin.install_symlink Dir["#{libexec}/bin/*"]
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/sofar --version")
    # The native core, not the JavaScript shim, is on PATH. It owns hook
    # shapes only (no --version), so ask the file, not the binary.
    refute_match(/script/, shell_output("file -L #{bin}/sofar-core"))

    # Fold a real record: init must scaffold .sofar/. Catches a bundle that
    # resolves but cannot run.
    system bin/"sofar", "init", "--agents", "claude-code"
    assert_predicate testpath/".sofar", :directory?
  end
end
`
}

const HEADER = `# Homebrew formula for the sofar CLI. GENERATED by
# packaging/homebrew/formula.mjs — edit the template there, not this file.
#
# Published through the tap repo as Formula/sofar.rb; users run:
#   brew install usesofar/tap/sofar
#
# NOT destined for homebrew-core: core's notability bar (~75 stars /
# 30 forks / 30 watchers) is well above where the repo sits. A custom tap
# has no such bar and installs identically.
#
# Source of truth is the npm registry, not a GitHub release: the repo cuts
# no GitHub releases, and registry tarballs are immutable and already what
# npm/bun/pnpm users get. sofar.sh is the url; the platform's native core
# is a resource.
`

async function sha256Of(url) {
  const res = await fetch(url)
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`)
  return createHash('sha256').update(Buffer.from(await res.arrayBuffer())).digest('hex')
}

async function latestVersion() {
  const res = await fetch(`${REGISTRY}/sofar.sh/latest`)
  if (!res.ok) throw new Error(`sofar.sh latest: HTTP ${res.status}`)
  return (await res.json()).version
}

if (process.argv[1] !== undefined && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const args = process.argv.slice(2)
  const outAt = args.indexOf('--out')
  const out = outAt >= 0 ? args.splice(outAt, 2)[1] : join(dirname(fileURLToPath(import.meta.url)), 'sofar.rb')
  try {
    const version = args[0] ?? (await latestVersion())
    const urls = [tarballUrl('sofar.sh', version), ...BREW_PLATFORMS.map((p) => tarballUrl(packageName(p), version))]
    const sha256 = Object.fromEntries(await Promise.all(urls.map(async (u) => [u, await sha256Of(u)])))
    writeFileSync(out, renderFormula(version, sha256))
    console.log(`${out} -> sofar ${version}`)
  } catch (err) {
    console.error(`formula: ${err instanceof Error ? err.message : String(err)}`)
    process.exit(1)
  }
}
