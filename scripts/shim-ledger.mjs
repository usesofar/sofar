// Regenerate packages/engine/src/hooks/shipped-shims.ts (felt-latency L5, D12):
// the sha256 of every version of each hook shim sofar has ever written, read
// from git history (the source under packages/engine/src/hooks/ and this
// repo's installed copies under .claude/hooks/). SessionStart rewrites a
// repo's shim only when its bytes hash to one of these, so a shim the operator
// edited is never touched. Run after changing any shim: node scripts/shim-ledger.mjs
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = new URL('..', import.meta.url).pathname
const SRC = join(ROOT, 'packages/engine/src/hooks')
const git = (args) => execFileSync('git', args, { cwd: ROOT, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })
const sha = (buf) => createHash('sha256').update(buf).digest('hex')

const ledger = {}
for (const file of readdirSync(SRC).filter((f) => f.endsWith('.sh')).sort()) {
  const hashes = new Set([sha(readFileSync(join(SRC, file)))])
  for (const path of [`packages/engine/src/hooks/${file}`, `.claude/hooks/${file}`]) {
    for (const commit of git(['log', '--all', '--format=%H', '--', path]).split('\n').filter(Boolean)) {
      try {
        hashes.add(sha(execFileSync('git', ['show', `${commit}:${path}`], { cwd: ROOT, maxBuffer: 16 * 1024 * 1024, stdio: ['ignore', 'pipe', 'ignore'] })))
      } catch {
        // deleted in that commit
      }
    }
  }
  ledger[file] = [...hashes].sort()
}
const body = Object.entries(ledger)
  .map(([file, hashes]) => `  '${file}': [\n${hashes.map((h) => `    '${h}',`).join('\n')}\n  ],`)
  .join('\n')
writeFileSync(
  join(SRC, 'shipped-shims.ts'),
  `// generated by scripts/shim-ledger.mjs — do not hand-edit (felt-latency L5, D12)\n` +
    `/** sha256 of every version of each hook shim sofar has written, the current one included. */\n` +
    `export const SHIPPED_SHIMS: Readonly<Record<string, readonly string[]>> = {\n${body}\n}\n`,
)
console.log(Object.entries(ledger).map(([f, h]) => `${f}: ${h.length}`).join('\n'))
