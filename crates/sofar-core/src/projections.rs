/// A string field of an optional JSON object (`route.agent`, `verify.cmd`), as
/// the template's `${…}` would print it.
fn json_field(obj: Option<&Json>, key: &str) -> Option<String> {
    obj?.as_obj()?.get(key).map(crate::json::js_to_string)
}

/// `verifySuffix` (r1-fixes 3.1, D19).
fn verify_suffix(task: &TaskState) -> String {
    let mut parts: Vec<String> = Vec::new();
    if let Some(cmd) = json_field(task.verify.as_ref(), "cmd") {
        parts.push(format!("verify: `{cmd}`"));
    }
    if let Some(v) = &task.verification {
        parts.push(if v.result == "pass" {
            format!(
                "verified pass @{} (attempt {})",
                utf16_prefix(&v.checked_head, 7),
                number_to_string(v.attempt)
            )
        } else {
            format!(
                "verification {} (attempt {}{})",
                v.result,
                number_to_string(v.attempt),
                v.exit_code
                    .map(|c| format!(", exit {}", number_to_string(c)))
                    .unwrap_or_default()
            )
        });
    }
    if parts.is_empty() {
        String::new()
    } else {
        format!(" — {}", parts.join("; "))
    }
}

/// `routeSuffix` (session-driver 3.2).
fn route_suffix(task: &TaskState) -> String {
    let Some(route) = task.route.as_ref() else {
        return String::new();
    };
    let mut parts: Vec<String> = Vec::new();
    if let Some(agent) = json_field(Some(route), "agent") {
        parts.push(agent);
    }
    if let Some(model) = json_field(Some(route), "model") {
        parts.push(format!("model {model}"));
    }
    if let Some(effort) = json_field(Some(route), "effort") {
        parts.push(format!("effort {effort}"));
    }
    if parts.is_empty() {
        String::new()
    } else {
        format!(" — route: {}", parts.join(", "))
    }
}

/// `renderPlan`.
#[must_use]
pub fn render_plan(state: &InitiativeState) -> String {
    let mut lines: Vec<String> = vec![GENERATED_HEADER.to_owned(), String::new()];
    lines.push(format!("# Plan: {}", slug_or_unnamed(state)));
    lines.push(String::new());
    lines.push(format!(
        "Goal: {}",
        if state.goal.is_empty() {
            "(none recorded)"
        } else {
            &state.goal
        }
    ));
    lines.push(String::new());
    // The brief is its own file (memory-lead 4.3 part A, D45); brief.md holds it whole.
    if !state.brief.is_empty() {
        lines.push(format!(
            "Brief: the operator's words, {} chars, verbatim in brief.md; `sofar show brief¶<k>` prints one paragraph.",
            utf16_len(&state.brief)
        ));
        lines.push(String::new());
    }
    lines.push(format!(
        "Progress: {}",
        progress_text(task_progress(&state.phases))
    ));
    lines.push(String::new());
    if state.phases.is_empty() {
        lines.push("(no plan recorded yet — call sofar_update_plan)".to_owned());
        lines.push(String::new());
    }
    // A closed phase is one line here and whole in its shard (D45).
    for (k, phase) in state.phases.iter().enumerate() {
        let head = phase_head(phase);
        if is_closed_phase(phase) {
            lines.push(format!("{head} — its tasks in {}", phase_shard(k + 1)));
            lines.push(String::new());
            // Its note stays where its status is read (phase-lifecycle 2.1).
            if let Some(note) = &phase.note {
                lines.push(format!("> {note}"));
                lines.push(String::new());
            }
        } else {
            lines.push(head);
            lines.push(String::new());
            lines.extend(phase_body(phase));
        }
    }
    if let Some(active) = &state.current.active_phase {
        lines.push(format!("Active phase: {active}"));
    }
    if let Some(next) = &state.current.next_action {
        lines.push(format!("Next action: {next}"));
    }
    if let Some(blocked) = &state.current.blocked_on {
        lines.push(format!("Blocked on: {blocked}"));
    }
    doc(&lines)
}

/// `phaseShard`: `phases/P<k>.md`, k counting phases in plan order.
#[must_use]
pub fn phase_shard(k: usize) -> String {
    format!("phases/P{k}.md")
}

/// `isClosedPhase`: done or dropped — one line in the plan index.
#[must_use]
pub fn is_closed_phase(phase: &PhaseState) -> bool {
    phase.status == "done" || phase.status == "dropped"
}

/// `phaseHead`.
#[must_use]
pub fn phase_head(phase: &PhaseState) -> String {
    format!(
        "## {} [{}] — {} done",
        phase.name,
        phase.status,
        phase_fraction(task_progress([phase]))
    )
}

/// `phaseBody`: the note and task lines, then a blank line.
#[must_use]
pub fn phase_body(phase: &PhaseState) -> Vec<String> {
    let mut lines = Vec::new();
    if let Some(note) = &phase.note {
        lines.push(format!("> {note}"));
        lines.push(String::new());
    }
    for task in &phase.tasks {
        let bx = match task.status.as_str() {
            "done" => 'x',
            "dropped" => '-',
            _ => ' ',
        };
        let suffix = match task.status.as_str() {
            "active" | "blocked" | "dropped" => format!(" ({})", task.status),
            _ => String::new(),
        };
        lines.push(format!(
            "- [{bx}] {} {}{suffix}{}{}",
            task.id,
            task.title,
            route_suffix(task),
            verify_suffix(task)
        ));
    }
    lines.push(String::new());
    lines
}

/// `clip` of the index templates: UTF-16 units, an ellipsis in the last one.
fn index_clip(text: &str, max: usize) -> String {
    if utf16_len(text) > max {
        format!("{}…", utf16_prefix(text, max - 1))
    } else {
        text.to_owned()
    }
}

