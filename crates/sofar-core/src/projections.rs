/// `${n} ${noun}` with an `s` unless n is 1 (`plural` in status.ts and the
/// `n` helper of describeFreshness, whose irregular plural is passed in).
#[must_use]
pub fn plural_of(n: u64, noun: &str, plural: &str) -> String {
    format!("{n} {}", if n == 1 { noun } else { plural })
}

#[must_use]
pub fn plural(n: u64, noun: &str) -> String {
    format!("{n} {noun}{}", if n == 1 { "" } else { "s" })
}

/// The `+N more` sentinel the fold appends when an activity list hits its cap
/// (`/^\+(\d+) more$/`): the count it carries, as JS `Number` would read it.
fn more_sentinel(item: &str) -> Option<f64> {
    let digits = item.strip_prefix('+')?.strip_suffix(" more")?;
    if digits.is_empty() || !digits.bytes().all(|b| b.is_ascii_digit()) {
        return None;
    }
    digits.parse().ok()
}

/// `describeActivity`: "N files (a, b, +K more), M commands, tests pass, task changes: …".
#[must_use]
pub fn describe_activity(activity: &SessionActivity) -> String {
    let mut parts: Vec<String> = Vec::new();
    if !activity.files.is_empty() {
        let last = activity.files.last().expect("non-empty");
        #[allow(clippy::cast_precision_loss, reason = "list lengths are small")]
        let count = match more_sentinel(last) {
            Some(n) => (activity.files.len() - 1) as f64 + n,
            None => activity.files.len() as f64,
        };
        let noun = if count.to_bits() == 1.0f64.to_bits() {
            "file"
        } else {
            "files"
        };
        parts.push(format!(
            "{} {noun} ({})",
            number_to_string(count),
            activity.files.join(", ")
        ));
    }
    if activity.commands > 0 {
        let failed = match activity.failed {
            Some(f) if f > 0 => format!(" ({f} failed)"),
            _ => String::new(),
        };
        parts.push(format!("{}{failed}", plural(activity.commands, "command")));
    }
    if let Some(test) = &activity.last_test {
        parts.push(format!("tests {}", if test.ok { "pass" } else { "fail" }));
    }
    if !activity.task_changes.is_empty() {
        parts.push(format!(
            "task changes: {}",
            activity.task_changes.join(", ")
        ));
    }
    if parts.is_empty() {
        "(no mechanical events)".to_owned()
    } else {
        parts.join(", ")
    }
}

/// What the run lock says about an UNSTOPPED run (drive-visibility 2.3,
/// core/run-lock.ts `RunLiveness`). Only `sofar status` has one: a lock is not
/// in the record, so no generated file may render it.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RunLiveness {
    Held,
    Free,
    Absent,
}

/// `stopRequestsInForce` (drive-visibility 2.2): the stop requests whose id
/// sorts after the owner's adoption. One left behind for a driver that died
/// cannot stop the `--resume` that followed it.
#[must_use]
pub fn stop_requests_in_force(run: &RunState) -> Vec<&str> {
    run.stop_requests
        .iter()
        .filter(|id| id.as_str() > run.owner.id.as_str())
        .map(String::as_str)
        .collect()
}

/// `describeRun`: what launched the sessions, under which policy, the
/// handoffs by reason (first seen first), the verifications, and the fate.
/// `liveness` rewrites the fate of an unstopped run (drive-visibility 2.3):
/// held keeps "running"; free and absent replace it.
#[must_use]
#[allow(clippy::too_many_lines, reason = "a verbatim port of one template")]
pub fn describe_run(run: &RunState, liveness: Option<RunLiveness>) -> String {
    let policy = if run.policy == "threshold" {
        format!(
            "threshold {}%{}",
            run.threshold_pct
                .map_or_else(|| "?".to_owned(), number_to_string),
            run.context_window
                .map(|w| format!(" of {}", number_to_string(w)))
                .unwrap_or_default()
        )
    } else {
        "task policy".to_owned()
    };
    let mut by_reason: Vec<(&str, u64)> = Vec::new();
    for h in &run.handoffs {
        match by_reason.iter_mut().find(|(r, _)| *r == h.reason) {
            Some(slot) => slot.1 += 1,
            None => by_reason.push((&h.reason, 1)),
        }
    }
    let breakdown = by_reason
        .iter()
        .map(|(reason, n)| format!("{n} {reason}"))
        .collect::<Vec<_>>()
        .join(", ");
    let n = run.handoffs.len() as u64;
    let passes = run
        .verifications
        .iter()
        .filter(|v| v.result == "pass")
        .count();
    let checks = if run.verifications.is_empty() {
        String::new()
    } else {
        format!(
            ", {passes}/{} verification{} passed",
            run.verifications.len(),
            if run.verifications.len() == 1 {
                ""
            } else {
                "s"
            }
        )
    };
    let handoffs = format!(
        "{}{}{checks}",
        plural(n, "handoff"),
        if breakdown.is_empty() {
            String::new()
        } else {
            format!(" ({breakdown})")
        }
    );
    // Only the requests the owner must honour (drive-visibility 2.2): one
    // left for a driver that died is not a stop the resumed run is ignoring.
    let requests = stop_requests_in_force(run).len();
    let asked = format!(
        "stop requested{}",
        if requests > 1 {
            format!(" {requests} times")
        } else {
            String::new()
        }
    );
    let fate = if let Some(reason) = &run.stop_reason {
        format!(
            "stopped: {reason}{}",
            run.stop_note
                .as_ref()
                .map(|n| format!(" — {n}"))
                .unwrap_or_default()
        )
    } else if liveness == Some(RunLiveness::Free) {
        format!(
            "driver gone — no stop recorded and the run lock on this machine is free{}; --resume picks it up",
            if requests > 0 {
                format!("; {asked}, never acknowledged")
            } else {
                String::new()
            }
        )
    } else if liveness == Some(RunLiveness::Absent) {
        format!(
            "liveness unknown — no stop recorded and no run lock for it on this machine{}",
            if requests > 0 {
                format!("; {asked}, not yet stopped")
            } else {
                String::new()
            }
        )
    } else if requests > 0 {
        format!("running — {asked}, not yet stopped")
    } else {
        "running".to_owned()
    };
    // A resumed run says so, and at which epoch; one never resumed renders as before.
    let resumed = if run.owner.epoch > 1.0 {
        format!(", resumed (epoch {})", number_to_string(run.owner.epoch))
    } else {
        String::new()
    };
    format!(
        "run {} via {}, {policy}{resumed} — {handoffs}; {fate}",
        run.id, run.adapter
    )
}

/// `runDetailLines` (drive-visibility 2.3): what `sofar status` lists under a
/// run's line — its permission surface in full, then its handoffs and
/// adoptions on one timeline, by time (stable, so a record with no adoption
/// lists its handoffs exactly as before).
#[must_use]
pub fn run_detail_lines(run: &RunState) -> Vec<String> {
    let mut lines = Vec::new();
    if let Some(s) = &run.surface {
        let mut pinned: Vec<String> = Vec::new();
        if let Some(model) = surface_field(s, "model") {
            pinned.push(format!("model {model}"));
        }
        if let Some(effort) = surface_field(s, "effort") {
            pinned.push(format!("effort {effort}"));
        }
        lines.push(format!(
            "  permissions: {}{}",
            surface_field(s, "permission_mode").unwrap_or_else(|| "undefined".to_owned()),
            if pinned.is_empty() {
                String::new()
            } else {
                format!(", {}", pinned.join(", "))
            }
        ));
        for rule in surface_list(s, "allow") {
            lines.push(format!("    allow {rule}"));
        }
        for rule in surface_list(s, "deny") {
            lines.push(format!("    deny {rule}"));
        }
    }
    let mut timeline: Vec<(&str, String)> = Vec::new();
    for h in &run.handoffs {
        let task = h
            .task
            .as_ref()
            .map(|t| format!(", task {t}"))
            .unwrap_or_default();
        let tokens = h
            .tokens
            .map(|t| format!(", {} tokens", number_to_string(t)))
            .unwrap_or_default();
        let detail = h
            .detail
            .as_ref()
            .map(|d| format!(" ({d})"))
            .unwrap_or_default();
        timeline.push((
            &h.ts,
            format!(
                "  - {} session {} — {}{task}{tokens}{detail}",
                h.ts, h.session_id, h.reason
            ),
        ));
    }
    // An adoption that did not outrank every one before it never held the
    // run — a race another driver won — and says so.
    let mut highest = 1.0_f64;
    for a in &run.adoptions {
        let lost = if a.epoch <= highest {
            ", outranked — never in force"
        } else {
            ""
        };
        highest = highest.max(a.epoch);
        timeline.push((
            &a.ts,
            format!(
                "  - {} resumed — epoch {}{lost}",
                a.ts,
                number_to_string(a.epoch)
            ),
        ));
    }
    timeline.sort_by(|a, b| a.0.cmp(b.0));
    lines.extend(timeline.into_iter().map(|(_, line)| line));
    lines
}

/// A string field of the run's permission surface, as a template literal prints it.
fn surface_field(surface: &Json, key: &str) -> Option<String> {
    let value = surface.as_obj()?.get(key)?;
    Some(crate::json::js_to_string(value))
}

/// A list field of the run's permission surface (`allow`, `deny`), each entry as a template literal prints it.
fn surface_list(surface: &Json, key: &str) -> Vec<String> {
    surface
        .as_obj()
        .and_then(|o| o.get(key))
        .and_then(Json::as_arr)
        .map(|a| a.iter().map(crate::json::js_to_string).collect())
        .unwrap_or_default()
}

/// `describeFreshness`: "3 files, 1 task change" — zero kinds omitted, commands never.
#[must_use]
pub fn describe_freshness(counts: &FreshnessCounts) -> String {
    let mut parts: Vec<String> = Vec::new();
    if counts.files > 0 {
        parts.push(plural(counts.files, "file"));
    }
    if counts.tasks > 0 {
        parts.push(plural(counts.tasks, "task change"));
    }
    if counts.phases > 0 {
        parts.push(plural(counts.phases, "phase change"));
    }
    if counts.notes > 0 {
        parts.push(plural(counts.notes, "note"));
    }
    if counts.decisions > 0 {
        parts.push(plural(counts.decisions, "decision"));
    }
    if counts.memories > 0 {
        parts.push(plural_of(
            counts.memories,
            "promoted memory",
            "promoted memories",
        ));
    }
    if counts.reviews > 0 {
        parts.push(plural(counts.reviews, "review"));
    }
    parts.join(", ")
}

/// `standingRules`: every decision carrying a rule with its 1-based ordinal.
/// A rule a later rule replaced (`superseded_by`, r1-fixes 3.2, D25) is
/// skipped while `retire` holds — `SOFAR_RETIRE=off` renders it as before.
#[must_use]
pub fn standing_rules(decisions: &[DecisionState], retire: bool) -> Vec<(usize, &DecisionState)> {
    decisions
        .iter()
        .enumerate()
        .filter(|(_, d)| !(retire && d.superseded_by.is_some()))
        .filter(|(_, d)| d.rule.is_some())
        .map(|(i, d)| (i + 1, d))
        .collect()
}

/// `relevanceScore` (memory-lead D4): distinct lexicon stems `text` shares with `focus`.
#[must_use]
pub fn relevance_score(text: &str, focus: &[String]) -> usize {
    // The distinct terms of `lexicalCounts(text)` that are in the focus,
    // without building (or sorting) the counts; no focus scores nothing.
    if focus.is_empty() {
        return 0;
    }
    let mut hit = vec![false; focus.len()];
    crate::lexicon::for_each_term(text, |term| {
        if let Some(i) = focus.iter().position(|f| *f == term) {
            hit[i] = true;
        }
    });
    hit.iter().filter(|h| **h).count()
}

/// `rankByRelevance`: score descending, ties newest (highest ordinal) first — a
/// stable sort, as `Array.prototype.sort` is.
#[must_use]
pub fn rank_by_relevance<T: Clone>(
    items: &[(usize, T)],
    focus: &[String],
    text: impl Fn(&T) -> String,
) -> Vec<(usize, T)> {
    let mut scored: Vec<(usize, (usize, T))> = items
        .iter()
        .map(|(ordinal, item)| {
            (
                relevance_score(&text(item), focus),
                (*ordinal, item.clone()),
            )
        })
        .collect();
    scored.sort_by(|a, b| b.0.cmp(&a.0).then_with(|| b.1.0.cmp(&a.1.0)));
    scored.into_iter().map(|(_, item)| item).collect()
}

/// `nativeOriginMark` (memory-lead D13/D14): the mark every surface puts on
/// a memory whose words are native memory's, so no reader takes a model's
/// note for the operator's instruction. Empty for the rest.
#[must_use]
pub fn native_origin_mark(origin: Option<&str>) -> &'static str {
    if origin.is_some_and(|o| o.starts_with("claude-memory:")) {
        "(from Claude memory, not the operator's words) "
    } else {
        ""
    }
}

/// `retireEnabled`: `SOFAR_RETIRE=off` (also `0`, `false`) renders every
/// decision as if none were retired — read by the render callers, never the fold.
#[must_use]
pub fn retire_enabled() -> bool {
    let Some(raw) = std::env::var_os("SOFAR_RETIRE") else {
        return true;
    };
    let v = raw.to_string_lossy();
    let v = js_trim(&v).to_lowercase();
    !(v == "off" || v == "0" || v == "false")
}

/// `retiredOrdinals` (core/retire.ts): 1-based ordinals no longer in force —
/// superseded, or scoped by `until` to a task that resolved (done or dropped).
#[must_use]
pub fn retired_ordinals(state: &InitiativeState) -> Vec<usize> {
    let resolved: Vec<&str> = state
        .phases
        .iter()
        .flat_map(|p| p.tasks.iter())
        .filter(|t| matches!(t.status.as_str(), "done" | "dropped"))
        .map(|t| t.id.as_str())
        .collect();
    state
        .decisions
        .iter()
        .enumerate()
        .filter(|(_, d)| {
            d.superseded_by.is_some() || d.until.as_deref().is_some_and(|u| resolved.contains(&u))
        })
        .map(|(i, _)| i + 1)
        .collect()
}

/// Another record's rule as `<slug> D<n>·<sfx>` (r4-fixes U5).
fn repo_rule_handle(r: &crate::index_tier1::RepoRule) -> String {
    format!(
        "{} D{}·{}",
        r.initiative,
        number_to_string(r.ordinal),
        handle_suffix(&r.id)
    )
}

/// `standingConstraintLines`: rules VERBATIM (whitespace normalised, never
/// `repoRuleLines` (memory-lead 2.2, D8): other records' standing rules,
/// rendered after this record's own inside the constraints block. The same
/// words are one rule (restatements render once under every handle, newest
/// handle last); a rule this record already renders is not repeated. Most
/// relevant to the focus first, then newest; whole entries only, within
/// `budget`; with no room for one, a single pointer line.
#[must_use]
pub fn repo_rule_lines(
    rules: &[crate::index_tier1::RepoRule],
    budget: i64,
    focus: &[String],
    own: &[&DecisionState],
) -> Vec<String> {
    use crate::text::cmp_utf16;
    let key = |rule: &str, quote: Option<&str>| {
        format!("{}\u{0}{}", one_line(rule), one_line(quote.unwrap_or("")))
    };
    let handle_of = |r: &crate::index_tier1::RepoRule| {
        format!("{} D{}", r.initiative, number_to_string(r.ordinal))
    };
    let mine: std::collections::HashSet<String> = own
        .iter()
        .filter_map(|d| d.rule.as_deref().map(|rule| key(rule, d.quote.as_deref())))
        .collect();
    // Each handle formatted once, not per comparison: ordered by the bare
    // `<slug> D<n>` as before, rendered suffixed (r4-fixes U5).
    let mut sorted: Vec<(&crate::index_tier1::RepoRule, String)> =
        rules.iter().map(|r| (r, handle_of(r))).collect();
    sorted.sort_by(|(a, ha), (b, hb)| {
        if a.ts == b.ts {
            cmp_utf16(ha, hb)
        } else if cmp_utf16(&a.ts, &b.ts).is_lt() {
            std::cmp::Ordering::Less
        } else {
            std::cmp::Ordering::Greater
        }
    });
    // A Map in insertion order, as the TypeScript `Map` iterates.
    #[allow(
        clippy::type_complexity,
        reason = "a TypeScript Map entry, field for field"
    )]
    let mut merged: Vec<(&crate::index_tier1::RepoRule, Vec<String>, Vec<String>)> = Vec::new();
    let mut at: std::collections::HashMap<String, usize> = std::collections::HashMap::new();
    for (r, handle) in sorted {
        let k = key(&r.rule, r.quote.as_deref());
        if mine.contains(&k) {
            continue;
        }
        let shown = repo_rule_handle(r);
        if let Some(&i) = at.get(&k) {
            let (newest, handles, shown_handles) = &mut merged[i];
            handles.push(handle);
            shown_handles.push(shown);
            *newest = r; // the newest restatement dates the rule
        } else {
            at.insert(k, merged.len());
            merged.push((r, vec![handle], vec![shown]));
        }
    }
    if merged.is_empty() {
        return Vec::new();
    }
    let mut ranked: Vec<(&crate::index_tier1::RepoRule, String, usize, String)> = merged
        .into_iter()
        .map(|(r, handles, shown)| {
            let score = relevance_score(
                &format!("{} {}", r.rule, r.quote.as_deref().unwrap_or("")),
                focus,
            );
            (r, handles.join(", "), score, shown.join(", "))
        })
        .collect();
    ranked.sort_by(|a, b| {
        b.2.cmp(&a.2).then_with(|| {
            if a.0.ts == b.0.ts {
                cmp_utf16(&a.1, &b.1)
            } else if cmp_utf16(&a.0.ts, &b.0.ts).is_lt() {
                std::cmp::Ordering::Greater
            } else {
                std::cmp::Ordering::Less
            }
        })
    });
    let mut entries: Vec<String> = Vec::new();
    let mut used: i64 = 0;
    for (r, _, _, shown) in &ranked {
        let line = format!("- [{shown}] {}", render_rule(&r.rule, r.quote.as_deref()));
        #[allow(clippy::cast_possible_wrap, reason = "line lengths are small")]
        let len = utf16_len(&line) as i64;
        if used + len + 1 > budget {
            break;
        }
        entries.push(line);
        used += len + 1;
    }
    let rest = ranked.len() - entries.len();
    if entries.is_empty() {
        return vec![format!(
            "- …and {rest} more from other records (their decisions.md)"
        )];
    }
    let mut out = vec![format!(
        "Repo-wide rules from other records ({} of {}, most relevant first):",
        entries.len(),
        ranked.len()
    )];
    out.extend(entries);
    if rest > 0 {
        out.push(format!(
            "- …and {rest} more in other records (their decisions.md)"
        ));
    }
    out
}

/// clipped); a budget drops whole entries after the first with a pointer.
#[must_use]
pub fn standing_constraint_lines(
    decisions: &[DecisionState],
    budget: Option<usize>,
    retire: bool,
    focus: Option<&[String]>,
) -> Vec<String> {
    // The digest passes a focus (memory-lead D4): most relevant first, so the
    // budget drops the least relevant rules instead of the newest.
    let in_order = standing_rules(decisions, retire);
    let standing: Vec<(usize, &DecisionState)> = match focus {
        None => in_order,
        Some(focus) => rank_by_relevance(&in_order, focus, |d| {
            format!(
                "{} {}",
                d.rule.as_deref().unwrap_or(""),
                d.quote.as_deref().unwrap_or("")
            )
        }),
    };
    if standing.is_empty() {
        return Vec::new();
    }
    // A quoted rule has a source that outranks its wording (memory-lead D2);
    // the header says so only when one exists.
    let quoted = standing.iter().any(|(_, d)| d.quote.is_some());
    let law = if quoted {
        "obey verbatim; where a rule quotes the operator, the quote decides"
    } else {
        "obey verbatim"
    };
    let mut lines = vec![format!(
        "Standing constraints — {law} ({}):",
        standing.len()
    )];
    let mut used = 0;
    let mut shown = 0;
    for (ordinal, d) in &standing {
        // Check-suffixed (r4-fixes U5): the handle a merge cannot move onto another rule.
        let line = format!(
            "- [{}] {}",
            suffixed_handle(*ordinal, &d.id),
            render_rule(d.rule.as_deref().unwrap_or(""), d.quote.as_deref())
        );
        let len = utf16_len(&line);
        if let Some(b) = budget
            && shown > 0
            && used + len + 1 > b
        {
            break;
        }
        lines.push(line);
        used += len + 1;
        shown += 1;
    }
    if shown < standing.len() {
        lines.push(format!(
            "- …and {} more (see decisions.md)",
            standing.len() - shown
        ));
    }
    lines
}

/// `doc`: join, strip trailing newlines, add exactly one.
#[must_use]
pub fn doc(lines: &[String]) -> String {
    let joined = lines.join("\n");
    format!("{}\n", joined.trim_end_matches('\n'))
}

/// `clipDetect`: one-line normalisation, then a hard cap with the ellipsis inside it.
#[must_use]
pub fn clip_detect(text: &str, max: usize) -> (String, bool) {
    let line = one_line(text);
    if utf16_len(&line) <= max {
        return (line, false);
    }
    (
        format!("{}…", utf16_prefix(&line, max.saturating_sub(1))),
        true,
    )
}

#[must_use]
pub fn clip(text: &str, max: usize) -> String {
    clip_detect(text, max).0
}

/// `clipBlockDetect`: keeps line structure; the marker lands INSIDE the budget.
#[must_use]
pub fn clip_block_detect(text: &str, budget: usize, marker: &str) -> (String, bool) {
    let trimmed = js_trim(text);
    if utf16_len(trimmed) <= budget {
        return (trimmed.to_owned(), false);
    }
    let suffix = format!("\n{marker}");
    let keep = budget.saturating_sub(utf16_len(&suffix));
    let head = utf16_prefix(trimmed, keep);
    (format!("{}{suffix}", js_trim_end(&head)), true)
}

/// `taskProgress` (task-drop-state D1): drops are their own term.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct TaskProgress {
    pub done: u64,
    pub dropped: u64,
    pub total: u64,
    pub remaining: u64,
}

#[must_use]
pub fn task_progress<'a>(phases: impl IntoIterator<Item = &'a PhaseState>) -> TaskProgress {
    let mut p = TaskProgress {
        done: 0,
        dropped: 0,
        total: 0,
        remaining: 0,
    };
    for phase in phases {
        for task in &phase.tasks {
            p.total += 1;
            if task.status == "done" {
                p.done += 1;
            } else if task.status == "dropped" {
                p.dropped += 1;
            }
        }
    }
    p.remaining = p.total - p.done - p.dropped;
    p
}

/// `progressText`: the headline sentence, byte-identical without drops.
#[must_use]
pub fn progress_text(p: TaskProgress) -> String {
    if p.dropped == 0 {
        format!(
            "{}/{} tasks done ({})",
            p.done,
            p.total,
            pct(p.done, p.total, 0)
        )
    } else {
        format!(
            "{} done, {} dropped, {} remaining",
            p.done, p.dropped, p.remaining
        )
    }
}

/// `phaseFraction`: `1/2`, or `1/3 (1 dropped)`.
#[must_use]
pub fn phase_fraction(p: TaskProgress) -> String {
    let base = format!("{}/{}", p.done, p.total);
    if p.dropped == 0 {
        base
    } else {
        format!("{base} ({} dropped)", p.dropped)
    }
}

/// `pct`: floors, never 100% while work remains; drops count as resolved.
#[must_use]
pub fn pct(done: u64, total: u64, dropped: u64) -> String {
    if total == 0 {
        return "0%".to_owned();
    }
    let resolved = done + dropped;
    #[allow(clippy::cast_precision_loss, reason = "task counts are small")]
    let raw = ((resolved as f64 / total as f64) * 100.0).floor();
    if resolved == total {
        "100%".to_owned()
    } else {
        format!("{}%", number_to_string(raw.min(99.0)))
    }
}

/// `testOutcomeLine` (D24): `pass — npm test`, `fail (exit 1) — npm test`.
#[must_use]
pub fn test_outcome_line(test: &TestOutcome) -> String {
    let exit = match (test.ok, test.exit) {
        (false, Some(code)) => format!(" (exit {})", number_to_string(code)),
        _ => String::new(),
    };
    format!(
        "{}{exit} — {}",
        if test.ok { "pass" } else { "fail" },
        test.cmd
    )
}

fn slug_or_unnamed(state: &InitiativeState) -> &str {
    if state.slug.is_empty() {
        "(unnamed initiative)"
    } else {
        &state.slug
    }
}

