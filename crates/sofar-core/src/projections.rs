/// `renderSession`.
#[must_use]
pub fn render_session(state: &InitiativeState, session: &SessionState) -> String {
    let mut lines: Vec<String> = vec![GENERATED_HEADER.to_owned(), String::new()];
    lines.push(format!("# Session {}", session.id));
    lines.push(String::new());
    lines.push(format!("- Initiative: {}", slug_or_unnamed(state)));
    lines.push(format!("- Tool: {}", session.tool));
    if let Some(model) = &session.model {
        lines.push(format!("- Model: {model}"));
    }
    lines.push(format!("- Started: {}", session.started));
    let closed = session
        .closed_reason
        .as_ref()
        .map(|r| format!(" (closed: {r})"))
        .unwrap_or_default();
    lines.push(format!(
        "- Ended: {}",
        match &session.ended {
            Some(ended) => format!("{ended}{closed}"),
            None => "(in progress)".to_owned(),
        }
    ));
    if let Some(handoff) = &session.handoff {
        let detail = handoff
            .detail
            .as_ref()
            .map(|d| format!(" ({d})"))
            .unwrap_or_default();
        lines.push(format!(
            "- Driven: run {} — handed off: {}{detail}",
            handoff.run, handoff.reason
        ));
    }
    lines.push(String::new());
    lines.push("## Summary".to_owned());
    lines.push(String::new());
    if let Some(summary) = &session.summary {
        lines.push(summary.clone());
    } else if session.activity.is_some() {
        let fate = if session.ended.is_some() {
            "ended without write-back"
        } else {
            "no write-back yet"
        };
        lines.push(format!(
            "(none recorded — {fate}; derived resume point below)"
        ));
    } else {
        lines.push("(none recorded — session did not write back)".to_owned());
    }
    lines.push(String::new());
    lines.push("## Next action".to_owned());
    lines.push(String::new());
    lines.push(
        session
            .next_action
            .clone()
            .unwrap_or_else(|| "(none recorded)".to_owned()),
    );
    if let Some(activity) = &session.activity {
        lines.push(String::new());
        lines.push("## Activity (derived from mechanical events)".to_owned());
        lines.push(String::new());
        lines.push(format!("- Derived: {}", describe_activity(activity)));
        if !activity.files.is_empty() {
            lines.push("- Files:".to_owned());
            for file in &activity.files {
                lines.push(format!("  - {file}"));
            }
        }
        lines.push(format!(
            "- Commands run: {}{}",
            activity.commands,
            activity
                .failed
                .map(|f| format!(" ({f} failed)"))
                .unwrap_or_default()
        ));
        if let Some(test) = &activity.last_test {
            lines.push(format!("- Last test: {}", test_outcome_line(test)));
        }
        if !activity.task_changes.is_empty() {
            lines.push("- Task changes:".to_owned());
            for change in &activity.task_changes {
                lines.push(format!("  - {change}"));
            }
        }
    }
    doc(&lines)
}

