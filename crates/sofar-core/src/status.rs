/// `enforceStatusLimit`: anything over the limit is cut to fit, marker included.
#[must_use]
pub fn enforce_status_limit(text: &str) -> String {
    if utf16_len(text) <= STATUS_CHAR_LIMIT {
        return text.to_owned();
    }
    let marker = format!("\n{STATUS_TRUNCATION_MARKER}\n");
    format!(
        "{}{marker}",
        utf16_prefix(text, STATUS_CHAR_LIMIT - utf16_len(&marker))
    )
}

fn last_with_summary(sessions: &[SessionState]) -> Option<&SessionState> {
    sessions.iter().rev().find(|s| s.summary.is_some())
}

/// `lastUnwrittenWithActivity`: newest → oldest, the first session with
/// activity but no summary, unless a written-back session is newer.
fn last_unwritten_with_activity(sessions: &[SessionState]) -> Option<&SessionState> {
    for session in sessions.iter().rev() {
        if session.summary.is_some() {
            return None;
        }
        if session.activity.is_some() {
            return Some(session);
        }
    }
    None
}

/// `unwrittenSessions`: EVERY session with activity and no summary, newest first.
#[must_use]
pub fn unwritten_sessions(sessions: &[SessionState]) -> Vec<&SessionState> {
    sessions
        .iter()
        .filter(|s| s.summary.is_none() && s.activity.is_some())
        .rev()
        .collect()
}

/// `hasRealAlternative`: `over` is non-blank and not the
/// `(no alternative …` / `(none …` placeholder — `/^\(\s*(no alternative|none)/i`,
/// a non-unicode regex, so the case fold is ASCII-only (P3).
pub fn has_real_alternative(over: &str) -> bool {
    let t = js_trim(over);
    if t.is_empty() {
        return false;
    }
    let Some(rest) = t.strip_prefix('(') else {
        return true;
    };
    let rest = rest.trim_start_matches(is_js_whitespace);
    let lower_starts = |needle: &str| {
        rest.len() >= needle.len()
            && rest.is_char_boundary(needle.len())
            && rest[..needle.len()].eq_ignore_ascii_case(needle)
    };
    !(lower_starts("no alternative") || lower_starts("none"))
}

const fn task_mark(status: &str) -> &'static str {
    match status.as_bytes() {
        b"done" => "[x]",
        b"active" => "[~]",
        b"blocked" => "[!]",
        b"dropped" => "[-]",
        _ => "[ ]",
    }
}

