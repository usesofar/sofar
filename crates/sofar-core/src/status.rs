/// `openSessionFiles`: (session, file) pairs of every live session's activity,
/// the `+N more` sentinel skipped.
#[must_use]
pub fn open_session_files<'a>(
    state: &'a InitiativeState,
    also_live: Option<&str>,
) -> Vec<(&'a str, &'a str)> {
    let mut pairs = Vec::new();
    for session in &state.sessions {
        let live = session.ended.is_none() || also_live == Some(session.id.as_str());
        let Some(activity) = &session.activity else {
            continue;
        };
        if !live {
            continue;
        }
        for file in &activity.files {
            if file.starts_with('+') {
                continue;
            }
            pairs.push((session.id.as_str(), file.as_str()));
        }
    }
    pairs
}

/// `openSessionFileConflicts`: files ≥2 open sessions touched, sorted by
/// path in UTF-16 code-unit order (rust-core D6).
#[must_use]
pub fn open_session_file_conflicts(
    state: &InitiativeState,
    also_live: Option<&str>,
) -> Vec<FileConflict> {
    // File → its slot in `by_file`, so grouping is linear. The scan it
    // replaces made this O(pairs × distinct files): 17% of session-start at
    // team100, a cost only the port had (the TypeScript groups in a Map).
    let mut slot_of: std::collections::HashMap<&str, usize> = std::collections::HashMap::new();
    let mut by_file: Vec<(&str, Vec<String>)> = Vec::new();
    for (session, file) in open_session_files(state, also_live) {
        if let Some(&i) = slot_of.get(file) {
            by_file[i].1.push(session.to_owned());
        } else {
            slot_of.insert(file, by_file.len());
            by_file.push((file, vec![session.to_owned()]));
        }
    }
    let mut conflicts: Vec<FileConflict> = by_file
        .into_iter()
        .filter(|(_, sessions)| sessions.len() >= 2)
        .map(|(path, sessions)| FileConflict {
            path: path.to_owned(),
            sessions,
        })
        .collect();
    conflicts.sort_by(|a, b| cmp_utf16(&a.path, &b.path));
    conflicts
}

/// `overlappingWritebacks`: the wrapped sessions whose `next_action` lost the
/// last-writer race against the reference (the newest write-back, or the
/// named one), newest first.
#[must_use]
pub fn overlapping_writebacks(
    state: &InitiativeState,
    reference_session_id: Option<&str>,
) -> Vec<ParallelWriteback> {
    fn ended(s: &SessionState) -> &str {
        s.ended.as_deref().expect("wrapped")
    }
    fn next(s: &SessionState) -> &str {
        s.next_action.as_deref().expect("wrapped")
    }
    let wrapped: Vec<&SessionState> = state
        .sessions
        .iter()
        .filter(|s| s.ended.is_some() && s.next_action.is_some())
        .collect();
    if wrapped.len() < 2 {
        return Vec::new();
    }
    let mut reference: Option<&SessionState> =
        reference_session_id.and_then(|id| wrapped.iter().copied().find(|s| s.id == id));
    if reference.is_none() {
        let mut best = wrapped[0];
        for s in &wrapped {
            if cmp_utf16(ended(s), ended(best)).is_ge() {
                best = s;
            }
        }
        reference = Some(best);
    }
    let r = reference.expect("set above");
    let mut out: Vec<&SessionState> = wrapped
        .iter()
        .copied()
        .filter(|s| {
            !std::ptr::eq(*s, r)
                && next(s) != next(r)
                && cmp_utf16(&s.started, ended(r)).is_le()
                && cmp_utf16(ended(s), &r.started).is_ge()
        })
        .collect();
    out.sort_by(|a, b| cmp_utf16(ended(b), ended(a)));
    out.into_iter()
        .map(|s| ParallelWriteback {
            session_id: s.id.clone(),
            tool: s.tool.clone(),
            ended: ended(s).to_owned(),
            next_action: next(s).to_owned(),
        })
        .collect()
}

/// `staleActivePhases` (staleness-detection 1.2).
#[must_use]
pub fn stale_active_phases(state: &InitiativeState) -> Vec<StalePhase> {
    state
        .phases
        .iter()
        .filter(|p| p.status != "done" && p.status != "dropped" && !p.tasks.is_empty())
        .filter(|p| p.tasks.iter().all(|t| is_resolved_task_status(&t.status)))
        .map(|p| StalePhase {
            name: p.name.clone(),
            status: p.status.clone(),
            tasks_done: p.tasks.len(),
        })
        .collect()
}

